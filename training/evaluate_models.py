"""Evaluate the preserved V1/V2 artifacts on the notebook's chronological split.

This script never fits or writes a model. It loads the existing model files and
compares them with the notebook's previous-day baseline on the same held-out
rows generated by ``generate_dataset.py``.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import joblib
import pandas as pd
from sklearn.metrics import mean_absolute_error


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_DATASET = PROJECT_ROOT / "training" / "synthetic_demand.csv"
V1_FEATURES = [
    "previous_day_demand",
    "previous_week_demand",
    "rolling_7_day_avg",
]
V2_FEATURES = V1_FEATURES + ["day_of_week"]
REPORTED_MAES = {
    "V1 MAE": 2.22,
    "V2 MAE": 2.09,
    "Previous-day baseline MAE": 2.31,
}


def evaluate(dataset_path: Path) -> dict[str, float]:
    data = pd.read_csv(dataset_path)
    required = {"demand", *V2_FEATURES}
    missing = sorted(required.difference(data.columns))
    if missing:
        raise ValueError(f"Dataset is missing required columns: {', '.join(missing)}")
    if data.empty:
        raise ValueError("Dataset is empty.")

    # Exactly matches the notebook: int(len(df) * 0.8), preserving row order.
    split = int(len(data) * 0.8)
    if split <= 0 or split >= len(data):
        raise ValueError("Dataset needs at least two rows for a chronological split.")
    train, test = data.iloc[:split], data.iloc[split:]
    y_test = test["demand"]

    artifacts = {
        "V1 MAE": (PROJECT_ROOT / "demand_model.joblib", V1_FEATURES),
        "V2 MAE": (PROJECT_ROOT / "demand_model_v2.joblib", V2_FEATURES),
    }
    measured: dict[str, float] = {}
    for metric_name, (artifact_path, features) in artifacts.items():
        if not artifact_path.is_file():
            raise FileNotFoundError(f"Model artifact not found: {artifact_path}")
        model = joblib.load(artifact_path)
        artifact_features = list(getattr(model, "feature_names_in_", features))
        if artifact_features != features:
            raise ValueError(
                f"{artifact_path.name} feature order is {artifact_features}; "
                f"expected {features}."
            )
        prediction = model.predict(test[features])
        measured[metric_name] = float(mean_absolute_error(y_test, prediction))

    baseline_prediction = test["previous_day_demand"].to_numpy()
    measured["Previous-day baseline MAE"] = float(
        mean_absolute_error(y_test, baseline_prediction)
    )

    print(f"Dataset: {dataset_path.resolve()}")
    print(f"Chronological rows: {len(data)} total; {len(train)} train; {len(test)} test")
    print(f"Split: first {split} rows train, remaining rows test (80/20 by row count)")
    for name, result in measured.items():
        reported = REPORTED_MAES[name]
        print(
            f"{name}: {result:.10f} (reported {reported:.2f}; "
            f"difference {result - reported:+.10f}; rounded {result:.2f})"
        )
    print("Models were loaded from the existing artifacts; no fitting or saving occurred.")
    return measured


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--dataset", type=Path, default=DEFAULT_DATASET,
        help=f"CSV generated from the notebook logic (default: {DEFAULT_DATASET})",
    )
    args = parser.parse_args()
    evaluate(args.dataset.expanduser().resolve())


if __name__ == "__main__":
    main()
